"""Build the production stylesheet for the neobrutalism brutal-a design from the handoff's ui.css.

- keeps only rules that can apply to brutal-a (drops neumorphism/neon/other-layout/preview-only selectors)
- rewrites light-dark(a,b): the base rule gets `a`; a twin rule under :root[data-bd-scheme="dark"] gets `b`
  (light-dark() needs Chrome 123+; this works on every browser that runs the app)
- drops .ck-* rules (the chicken game ships its own stylesheet from the chicken design package)
usage: extract_css.py ui.css out.css
"""
import re, sys

EXCLUDE = re.compile(r"\.st-(?!brutal\b)|\.bd-night|\.lay-2|\.lay-3|\.ng-lay-|\.bd-style-tabs|\.bd-page-tabs|\.bd-stage|\.viz-|\.export-|\.handoff|\.rt-toolbar|\.nav-pills|\.form-select|\.form-label|\.ck-|\.bd-v\b|\[data-design=\"brutal-[bc]\"\]|\.bd-variant-")
DARK = ':root[data-bd-scheme="dark"]'


def split_top(s, sep=","):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


def parse(css):
    """-> list of (prelude, body) where body is str for declarations or list for nested blocks."""
    items, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        inner = css[j + 1:k - 1]
        if prelude.startswith("@media") or prelude.startswith("@supports") or prelude.startswith("@container"):
            items.append((prelude, parse(inner)))
        else:
            items.append((prelude, inner))
        i = k
    return items


def resolve(value, which):
    while "light-dark(" in value:
        a = value.find("light-dark(")
        depth, k = 0, a + len("light-dark")
        for k in range(a + len("light-dark"), len(value)):
            if value[k] == "(":
                depth += 1
            elif value[k] == ")":
                depth -= 1
                if depth == 0:
                    break
        args = split_top(value[a + len("light-dark("):k])
        value = value[:a] + args[which].strip() + value[k + 1:]
    return value


def decls(body):
    return [d for d in split_top(body, ";") if d.strip()]


def rules(items):
    out = []
    for prelude, body in items:
        if isinstance(body, list):
            inner = rules(body)
            if inner:
                out.append(prelude + "{" + "".join(inner) + "}")
            continue
        if prelude.startswith("@keyframes") or prelude.startswith("@font-face"):
            if not re.search(r"ck-", prelude):
                out.append(prelude + "{" + body + "}")
            continue
        sels = [s.strip() for s in split_top(prelude) if s.strip() and not EXCLUDE.search(s)]
        if not sels:
            continue
        ds = decls(body)
        light = ";".join(resolve(d, 0) for d in ds)
        out.append(",".join(sels) + "{" + light + "}")
        dark = [resolve(d, 1) for d in ds if "light-dark(" in d]
        if dark:
            out.append(",".join(DARK + " " + s for s in sels) + "{" + ";".join(dark) + "}")
    return out


css = open(sys.argv[1]).read()
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
# @keyframes need raw handling: parse() treats them as plain rules with nested braces kept as text
out = rules(parse(css))
open(sys.argv[2], "w").write("/* generated by tools/extract_css.py from the neobrutalism handoff ui.css: do not edit by hand */\n" + "\n".join(out) + "\n")
print(len(out), "rules")
