// Generates src/bd/icons.ts from the handoff's pinned lucide 1.17.0 bundle (only the icons the app uses).
// usage: node gen_icons.mjs <lucide-1.17.0.js> <out.ts> name...
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
const [, , src, out, ...names] = process.argv;
const ctx = { globalThis: {} };
ctx.self = ctx.globalThis;
vm.runInNewContext(readFileSync(src, "utf8"), ctx);
const lucide = ctx.globalThis.lucide;
const pascal = (n) => n.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const lines = names.sort().map((n) => {
  const node = lucide.icons[pascal(n)];
  if (!node) throw new Error("missing icon " + n);
  return `\t"${n}": ${JSON.stringify(node.map(([tag, attrs]) => [tag, attrs]))},`;
});
writeFileSync(out, `/* Generated by tools/gen_icons.mjs from lucide v1.17.0 (ISC, see public/bd/LUCIDE-LICENSE). Do not edit. */
export type IconNode = [string, Record<string, string | number>][];
export const ICONS = {
${lines.join("\n")}
} satisfies Record<string, IconNode>;
export type IconName = keyof typeof ICONS;
`);
console.log(names.length, "icons");
