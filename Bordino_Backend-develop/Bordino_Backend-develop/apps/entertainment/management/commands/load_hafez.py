class Command(BaseCommand):
    help = "بارگذاری غزل‌های حافظ در دیتابیس"

    def handle(self, *args, **kwargs):
        created = 0
        for ghazal in HAFEZ_GHAZALS:
            obj, was_created = FortuneReading.objects.get_or_create(
                question=ghazal["question"],
                defaults={"result": ghazal["result"], "type": FortuneReading.ReadingType.HAFEZ},
            )
            if was_created:
                created += 1

        total = FortuneReading.objects.count()
        print(f"Done: {created} new, {total} total in DB")
