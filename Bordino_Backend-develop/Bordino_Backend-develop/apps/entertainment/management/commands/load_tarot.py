class Command(BaseCommand):
    help = "Load the 22 Major Arcana tarot cards (idempotent)."

    def handle(self, *args, **options):  # pylint: disable=unused-argument
        created, updated = 0, 0
        for order, name, symbol, interpretation in MAJOR_ARCANA:
            _, was_created = TarotCard.objects.update_or_create(
                order=order,
                defaults={
                    "name": name,
                    "symbol": symbol,
                    "interpretation": interpretation,
                },
            )
            if was_created:
                created += 1
            else:
                updated += 1
        self.stdout.write(
            self.style.SUCCESS(f"Tarot cards loaded: {created} created, {updated} updated.")
        )
